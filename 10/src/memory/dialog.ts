/** 12 пар = 24 сообщения: 12 фактов в начале, 8 «шумных» сообщений в конце. */
export function buildMemoryDialog(): ChatMessage[] {
  return TURNS.flatMap(turn => [
    { role: 'user', content: turn.user } satisfies ChatMessage,
    { role: 'assistant', content: turn.assistant } satisfies ChatMessage,
  ])
}

export function memoryDialogTurns(): number {
  return TURNS.length
}

/** Нормализация для сравнения ответа модели с ожидаемой деталью. */
export function normalizeForMatch(text: string): string {
  return text
    .toLowerCase()
    .replace(/ё/g, 'е')
    .replace(/[^\p{L}\p{N}]+/gu, ' ')
    .replace(/\s+/g, ' ')
    .trim()
}

export function answerMentions(detail: MemoryDetail, answer: string): boolean {
  const normalized = normalizeForMatch(answer)
  if (!normalized) return false
  return detail.keywords.some(keyword => {
    const normalizedKeyword = normalizeForMatch(keyword)
    return normalizedKeyword.length > 0 && normalized.includes(normalizedKeyword)
  })
}

function messageText(message: ChatMessage): string {
  const parts: string[] = []
  if (message.content) parts.push(message.content)
  for (const call of message.tool_calls ?? []) {
    parts.push(call.function.name, call.function.arguments)
  }
  return parts.join(' ')
}

export function messagesContainDetail(
  messages: ChatMessage[],
  detail: MemoryDetail,
): boolean {
  return messages.some(message => answerMentions(detail, messageText(message)))
}
